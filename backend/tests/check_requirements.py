"""Ensure the hash-pinned image dependencies come from the committed uv lock."""
from pathlib import Path
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
path = Path(sys.argv[1]) if len(sys.argv) == 2 else root / 'requirements.txt'
if len(sys.argv) > 2:
    raise SystemExit('Usage: python tests/check_requirements.py [REQUIREMENTS_FILE]')
result = subprocess.run(
    ['uv', 'export', '--locked', '--no-dev', '--no-emit-project', '--no-header'],
    cwd=root, capture_output=True, text=True, check=True,
)
actual = path.read_text().splitlines()
# uv's generated command header contains the output filename, which is not
# relevant to the package set or hashes.
if len(actual) >= 2 and actual[0].startswith('# This file was autogenerated by uv') and actual[1].startswith('#    uv export '):
    actual = actual[2:]
if actual != result.stdout.splitlines():
    raise SystemExit('requirements.txt differs from uv.lock; regenerate the hash-pinned export')
print('Container requirements match the locked production dependencies.')
