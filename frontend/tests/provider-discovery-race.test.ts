import '@angular/compiler';
import { strict as assert } from 'node:assert';
import { ChangeDetectorRef, Injector, runInInjectionContext } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { Subject } from 'rxjs';
import { AppComponent } from '../src/app/app.component';
import { SessionLifecycle } from '../src/app/session-lifecycle';

const requests: {url:string; result:Subject<any>}[] = [];
const send = (url:string) => {const result = new Subject<any>(); requests.push({url,result}); return result.asObservable();};
const injector = Injector.create({providers:[SessionLifecycle, {provide:HttpClient,useValue:{post:send,put:send,delete:send}}, {provide:ChangeDetectorRef,useValue:{markForCheck(){}}}]});
const component = runInInjectionContext(injector, () => new AppComponent());
component.login = () => {};
(globalThis as any).confirm = () => true;
const provider = {id:1, name:'Example', provider_type:'openai', model_group:'general' as const, configured:true, active:true};
const other = {...provider, id:2, name:'Other'};
component.selectDiscovery(provider); component.discoverProvider();
component.rotateId = 1; component.rotateSecret = 'fake'; component.rotateProvider();
requests[0].result.next({models:[{id:'old', name:'old'}],partial:false});
assert.equal(component.discoveryResult, null);
requests[1].result.next({}); assert.equal(component.discoveryProvider?.configured, true);
component.discoverProvider(); component.removeProviderKey(provider);
requests[2].result.next({models:[{id:'stale', name:'stale'}],partial:false}); assert.equal(component.discoveryResult, null);
requests[3].result.next({}); assert.equal(component.discoveryProvider?.configured, false);
component.selectDiscovery(provider); component.discoverProvider(); component.toggleProvider(provider);
requests[4].result.next({models:[{id:'stale', name:'stale'}],partial:false}); assert.equal(component.discoveryResult, null);
requests[5].result.next({}); assert.equal(component.discoveryProvider?.active, false);
component.selectDiscovery(provider); component.discoverProvider(); component.rotateId = 1; component.rotateProvider();
component.selectDiscovery(other); requests[7].result.next({});
assert.equal(component.discoveryProvider?.id, 2); assert.equal(component.discoveryProvider?.active, true);
console.log('Provider key and activation changes invalidate only their own pending model discovery.');
